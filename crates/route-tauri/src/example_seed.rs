//! Example data seeder — produces a realistic, fully-populated sample
//! project so the user can see the entire feature surface in one view.
//!
//! Used by the "Try example project" button on the welcome page. Creates
//! a directory under `target_dir`, writes a small, plausible source tree,
//! then runs a curated sequence of operations:
//!
//!   1.  Initialize a basic-mode repo at the project root.
//!   2.  Several user commits on `main` (incremental, normal cadence).
//!   3.  One user checkpoint at the half-way point.
//!   4.  An AI-driven commit with operator="ai:claude" + prompt body.
//!   5.  Another user commit, then an undo (rollback).
//!   6.  A sandbox branch + a couple of changes on it.
//!   7.  An inherited branch + a couple of changes on it.
//!   8.  A redo on main to show the chain recovering.
//!   9.  A second AI commit, this time introducing a "conflicted file".
//!
//! Every commit is real (no synthetic timestamps) — the seeder sleeps a
//! few milliseconds between calls so the file-watcher / diff-summary
//! pipeline has time to see each write. The result is a project the
//! frontend can render with full branches, checkpoints, AI operators,
//! rollbacks, and a multi-branch history.

