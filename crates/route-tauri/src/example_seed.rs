    let cart_model = prisma_model("Cart", "  userId String     @unique\n  user   User       @relation(fields: [userId], references: [id])\n  items  CartItem[]");
    let cart_item_model = prisma_model("CartItem", "  cartId    String\n  cart      Cart    @relation(fields: [cartId], references: [id])\n  productId String\n  product   Product @relation(fields: [productId], references: [id])\n  quantity  Int");
    let analytics_model = prisma_model("AnalyticsEvent", "  name      String\n  props     Json?\n  sessionId String?\n  userId    String?");
