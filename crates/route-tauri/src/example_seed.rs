fn run_on_big_stack<F, R>(f: F) -> Result<R, String>
where
    F: FnOnce() -> Result<R, String> + Send + 'static,
    R: Send + 'static,
{
    let join = std::thread::Builder::new()
        .name("route-seed-bigstack".into())
        .stack_size(64 * 1024 * 1024)
        .spawn(f)
        .map_err(|e| format!("failed to spawn big-stack thread: {e}"))?
        .join();
    match join {
        Ok(inner) => inner,
        Err(_) => Err("seed thread panicked".to_string()),
    }
}

pub fn seed_example_on_big_stack(
    target_dir: String,
) -> Result<(BasicRepository, PathBuf), String> {
    run_on_big_stack(move || -> Result<(BasicRepository, PathBuf), String> {
        let target = PathBuf::from(&target_dir);
        fs::create_dir_all(&target).map_err(|e| e.to_string())?;
        let project_path = target.join(EXAMPLE_PROJECT_NAME);
        let project_path_for_repo = project_path.clone();
        let repo = seed_example(&project_path_for_repo).map_err(|e| e.to_string())?;
        Ok((repo, project_path))
    })
}

pub fn seed_example_command(
    target_dir: String,
    state: &AppState,
) -> Result<crate::commands::StatusDto, String> {
    tracing::info!(target_dir = %target_dir, "seed_example_command: starting");
    let (repo, project_path) = match seed_example_on_big_stack(target_dir) {
        Ok(v) => {
            tracing::info!(path = %v.1.display(), "seed_example_on_big_stack: ok");
            v
        }
        Err(e) => {
            tracing::error!(error = %e, "seed_example_on_big_stack: failed");
            return Err(e);
        }
    };
    let dto = match crate::commands::build_status(&repo) {
        Ok(d) => d,
        Err(e) => {
            tracing::error!(error = %e, "build_status: failed");
            return Err(e.to_string());
        }
    };
    state.set_repo(repo);
    if let Ok(mut p) = state.project_path.lock() {
        *p = Some(project_path);
    }
    tracing::info!("seed_example_command: completed");
    Ok(dto)
}

