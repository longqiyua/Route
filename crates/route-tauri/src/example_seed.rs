//! Example data seeder — produces a realistic, heavily-populated sample
//! project so the user can see the entire feature surface in one view.
//!
//! Used by the "Try example project" / "Sandbox" button on the welcome page.
//! Creates a full Next.js e-commerce project ("NextShop") with:
//!
//!   - 100+ source files across a realistic directory tree
//!   - ~36 commits on main (v0.1 → v3.2 progression)
//!   - 5 branches: main, develop, feature/dark-mode, feature/i18n, sandbox/experiments
//!   - 4 checkpoints at key milestones
//!   - 6 AI commits (ai:claude, ai:gpt) with prompt bodies
//!   - 2 undo/redo cycles on main
//!   - 1 sandbox branch (never merged)
//!   - 2 inherited feature branches
//!   - 1 develop branch with merge commits
//!
//! Every commit is real — the seeder sleeps a few milliseconds between calls
//! so the file-watcher / diff-summary pipeline has time to see each write.

